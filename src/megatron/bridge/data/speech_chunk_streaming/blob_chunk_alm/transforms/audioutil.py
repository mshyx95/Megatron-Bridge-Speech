"""Audio utilities"""

import io
import numpy as np
import soundfile as sf
from scipy.io.wavfile import write


class AudioUtil:
    """
    Audio utilities class.
    """

    @staticmethod
    def read_wave(wavfile):
        """
        Read a wavefile from path/file-like object.

        Args:
            wavfile (str/filelike)

        Returns:
            data (numpy.array), sample_rate (int)).
        """
        return sf.read(wavfile)

    @staticmethod
    def read_wavebytes(data):
        """
        Read a wavefile from byte string.

        Args:
            data (bytes): data to read from.

        Returns:
            data (numpy.array), sample_rate (int)).
        """
        return sf.read(io.BytesIO(data))

    @staticmethod
    def wave_to_file(wavefile, data, sample_rate):
        """
        Write a wavefile to a path/file-like object.

        Args:
            wavefile (str/filelike): file to write to.
            data (numpy.array): data to write.
            sample_rate (int): sample rate.
        """
        sf.write(wavefile, data, sample_rate)

    @staticmethod
    def wave_to_bytes(data, sample_rate):
        """
        Write a wavefile to a byte string.

        Args:
            data (numpy.array): data to write.
            sample_rate (int): sample rate.

        Returns:
            bytes string
        """
        with io.BytesIO() as buff:
            sf.write(buff, data, sample_rate)
            return buff.getvalue()

    @staticmethod
    def wave_to_bytes_scipy(audio_numpy_array, audio_sr):
        """
        Write a wavefile to a byte string.
        Same method as above, but the sf one doesn't work for some reason.

        Args:
            audio_numpy_array (numpy.ndarray): data to write.
            audio_sr (int): sample rate.

        Returns:
            bytes string
        """
        bytes_wav = b""
        byte_io = io.BytesIO(bytes_wav)
        write(byte_io, audio_sr, audio_numpy_array)
        return byte_io.read()

    @staticmethod
    def wave_to_bytes_scipy_16bit(audio_numpy_array, audio_sr):
        """
        The data generated by the wave_to_bytes_scipy method is not 16bit,
        so the output data is converted to 16bit format.

        Args:
            audio_numpy_array (numpy.ndarray): data to write.
            audio_sr (int): sample rate.

        Returns:
            bytes string
        """
        bytes_wav = b""
        byte_io = io.BytesIO(bytes_wav)
        write(byte_io, audio_sr, AudioUtil.float2pcm(audio_numpy_array))
        return byte_io.read()

    @staticmethod
    def float2pcm(sig, dtype="int16"):
        """Convert floating point signal with a range from -1 to 1 to PCM.
        Any signal values outside the interval [-1.0, 1.0) are clipped.
        No dithering is used.
        Note that there are different possibilities for scaling floating
        point numbers to PCM numbers, this function implements just one of
        them.  For an overview of alternatives see
        http://blog.bjornroche.com/2009/12/int-float-int-its-jungle-out-there.html

        Args:
            sig : array_like
                Input array, must have floating point type.
            dtype : data type, optional
                Desired (integer) data type.

        Returns
            numpy.ndarray
                Integer data, scaled and clipped to the range of the given
                *dtype*.
        """
        sig = np.asarray(sig)
        if sig.dtype.kind != "f":
            raise TypeError("'sig' must be a float array")
        dtype = np.dtype(dtype)
        if dtype.kind not in ["i", "u"]:
            raise TypeError("'dtype' must be an integer type")

        i = np.iinfo(dtype)
        abs_max = 2 ** (i.bits - 1)
        offset = i.min + abs_max
        return (sig * abs_max + offset).clip(i.min, i.max).astype(dtype)
