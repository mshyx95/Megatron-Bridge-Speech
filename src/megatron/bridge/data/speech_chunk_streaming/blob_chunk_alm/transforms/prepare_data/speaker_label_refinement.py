    def map_segment_spkid_to_words(self, seg_spk_ids, seg2words):
        diarized_words = []
        for seg_i, seg_spkid in enumerate(seg_spk_ids):
            for word in seg2words[seg_i]:
                diarized_words.append(copy.deepcopy(word))
                diarized_words[-1].append(int(seg_spkid))

        return sorted(diarized_words, key=lambda x: x[1])

    def _get_word_timing(self, chunks, wavs, fs):
        """Perform forced alignment to get word timing for each chunk.
        Inputs:
            chunks: list of chunks, each chunk is [start_time, end_time, hypothesis text with speaker ids]
        Outputs:
            chunks_with_timing: list of chunks, each chunk is list of [start_time, end_time, word, spk_id]
        """
        chunks_with_timing = []
        for chunk in tqdm.tqdm(chunks):
            chunk_start = chunk[0]
            hyp = chunk[2].replace("\xa0", " ")  # replace non-breaking space with normal space
            hyp = hyp.replace("\n", " ").strip()
            hyp = re.sub(r'\s+', ' ', hyp)  # normalize multiple spaces to
            hyp = re.sub(r"<SPK-.+?>", "! ", hyp)  # use '!' as placeholder for speaker change. This will be used to do segmentation later.
            # remove initial and ending '! '
            hyp = re.sub(r"^!+\s*", "", hyp)
            hyp = re.sub(r"\s*!+$", "", hyp)
            word_list = hyp.strip().split()  
            # word_list_with_spkid, _, _ = parse_speaker_id_in_hyp(hyp)
            # word_list = [w[0] for w in word_list_with_spkid]

            start_sample = int(chunk[0] * fs)
            end_sample = int(chunk[1] * fs)
            wav = wavs[0, start_sample:end_sample].cpu().numpy()

            word_list_with_timing = self.aligner(wav, word_list)  # perform forced alignment
            word_list_with_timing = [
                [round(w[0] + chunk_start, 2), round(w[1] + chunk_start, 2), w[2]]
                for w in word_list_with_timing
            ]
            chunks_with_timing.append(word_list_with_timing)

            # word_list_with_timing_spk = []
            # for w_timing, w_spk in zip(word_list_with_timing, word_list_with_spkid):
            #     assert w_timing[2] == w_spk[0], "Word mismatch between timing and speaker id"
            #     word_list_with_timing_spk.append(
            #         [w_timing[0] + chunk_start, w_timing[1] + chunk_start, w_spk[0], w_spk[1]])
            # chunks_with_timing.append(word_list_with_timing_spk)

        return chunks_with_timing

    def merge_broken_lines(self, chunks):
        """Merge broken lines in the closed captions, e.g. break a sentence into multiple lines.
        Inputs:
            chunks: list of [start_time, end_time, word]
        Outputs:
            merged_chunks: list of [start_time, end_time, word]
        """
        merged_chunks = []
        current_chunk = None

        for chunk in chunks:
            if current_chunk is None:
                current_chunk = chunk
            else:
                # If the current chunk and the new chunk overlap, merge them
                prev_sentence_end_with_punct = re.match(r".*[\.\!\?\u3002\uff1f\uff01]$", current_chunk[2].strip())
                curr_sentence_start_with_lower = re.match(r"^[a-z\u3040-\u309F\u30A0-\u30FF].*", chunk[2].strip())
                time_gap_criteria = chunk[0] - current_chunk[1] <= 1.0  # 1.0 seconds gap threshold
                if not prev_sentence_end_with_punct and time_gap_criteria and curr_sentence_start_with_lower:
                    current_chunk[1] = max(current_chunk[1], chunk[1])
                    current_chunk[2] += " " + chunk[2]
                else:
                    merged_chunks.append(current_chunk)
                    current_chunk = chunk

        if current_chunk is not None:
            merged_chunks.append(current_chunk)

        # for seg in merged_chunks:
        #     print(f"{seg[0]}\t{seg[1]}\t{seg[2]}")

        return merged_chunks

    def __call__(self, hyp, wav, fs=16000):
        wavs = torch.tensor(wav).unsqueeze(0).to(self.device)
        _, dvecs = self.dvec_extractor(wavs)

        # extract segments from hyp
        chunks = [seg.split("\t") for seg in hyp]
        chunks = [[float(seg[0]), float(seg[1]), seg[2]] for seg in chunks]
        chunks = self.merge_broken_lines(chunks)

        # perform forced alignment to get word timing
        chunks_with_timing = self._get_word_timing(chunks, wavs, fs)

        # get dvectors for each speaker in each chunk
        # seg_dvecs, seg_times, seg2local_cluster = self.gen_pseudo_segments(chunks_with_timing, dvecs)
        seg_dvecs, seg_times, seg2words = self.gen_segments(chunks_with_timing, dvecs)

        # run clustering
        seg_spk_ids = self._run_beamsearch(
            self.beam_search_cfg, seg_dvecs, seg_times, min_num_speakers=1, max_num_speakers=100,
        )

        # map speaker IDs of pseudo segments back to local clusters
        diarized_words = self.map_segment_spkid_to_words(seg_spk_ids, seg2words)

        # self.display_diarization_outputs(diarized_words)

        return diarized_words

    def _run_beamsearch(
        self, cfg, long_segs_dvec, long_seg_times, min_num_speakers, max_num_speakers
    ):
        logger.info("Run speaker beam search based clustering...")
        # TO DO: enforce maximum number of speakers in beam search

        bs_tagger = BeamSearch(
            profile_dir=None,
            invited_list=[],
            min_profile_duration=cfg.min_profile_duration,
            profile_weight=cfg.profile_weight,
            new_cluster_cosine_sim=cfg.new_cluster_cosine_sim,
            kappa=cfg.kappa,
            spk_change_prior=cfg.spk_change_prior,
            new_cluster_prior=cfg.new_cluster_prior,
            beam_size=cfg.beamwidth,
            look_ahead=cfg.look_ahead,
            complexity_penalty=cfg.complexity_penalty,
            short_utt_ignore_dur=cfg.short_utt_ignore_dur,
            max_num_speakers=max_num_speakers,
        )

        # convert segments into a list of Segments objects to interface with beam search
        # also convert torch.tensor to numpy array
        # TO DO: make beam search native for pytorch so we can use GPU
        segments = [
            Segment(seg_time=np.array(seg_time), dvec=torch.mean(dvec, dim=0, keepdims=True).cpu().numpy().T)
            for dvec, seg_time in zip(long_segs_dvec, long_seg_times)
        ]

        if cfg.longest_first:
            durations = [seg.duration for seg in segments]
            segments_order = np.argsort(durations)[::-1]
            segments = [segments[i] for i in segments_order]

        for i in range(len(segments)):
            bs_tagger(segments[i : i + 1])

        _, cluster_label = bs_tagger.get_prediction()

        if cfg.longest_first:
            cluster_label2 = np.zeros(len(cluster_label))
            for sorted_idx, original_idx in enumerate(segments_order):
                cluster_label2[original_idx] = cluster_label[sorted_idx]
            cluster_label = cluster_label2

        return cluster_label

    def _dump_word_timing_for_debug(self, chunks_with_timing, out_file):
        """Dump word timing for debugging."""
        with open(out_file, "w") as f:
            for chunk in chunks_with_timing:
                for word in chunk:
                    f.write(f"{word[0]:.2f}\t{word[1]:.2f}\t{word[3]}:{word[2]}\n")
                # write chunk separator
                f.write(f"{chunk[-1][1]:.2f}\t{chunk[-1][1]+0.1:.2f}\tchunk_end\n")

